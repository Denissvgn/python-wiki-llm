def owned_behavior(source_root: Path, control: str) -> dict[str, Any]:
    """Falsify a wrong owned source variant using independently fixed outputs.

    Compilation, process completion, and behavioral acceptance are distinct.
    Only known fixture controls are supported; no target command is accepted.
    """
    if control not in _BEHAVIOR_CONTROLS:
        raise ValueError("unknown owned behavior control")
    root = source_root.resolve()
    _require(root.is_dir(), "owned source directory is missing")
    paths = list(root.rglob("*"))
    _require(len(paths) < 256 and not any(p.is_symlink() for p in paths), "invalid owned source tree")
    try:
        for path in paths:
            if path.is_file() and path.suffix == ".py":
                compile(path.read_text(encoding="utf-8"), str(path), "exec")
    except (SyntaxError, ValueError):
        return {"compiled": False, "process_exit": None, "oracle_passed": False,
                "model_execution_established": False}
    script = ('import json, sys\nsys.dont_write_bytecode = True\nsys.path.insert(0, sys.argv[1])\n'
              + _BEHAVIOR_CONTROLS[control]
              + '\nprint(json.dumps({"checks": checks, "oracle_passed": all(checks)}))\n')
    environment = {key: value for key, value in os.environ.items()
                   if key in {"PATH", "SYSTEMROOT", "WINDIR", "TMPDIR", "TEMP", "TMP"}}
    try:
        completed = subprocess.run([sys.executable, "-I", "-c", script, str(root)], cwd=root,
                                   capture_output=True, text=True, env=environment, timeout=5)
    except subprocess.TimeoutExpired:
        return {"compiled": True, "process_exit": None, "oracle_passed": False,
                "status": "timed-out", "model_execution_established": False}
    result = json.loads(completed.stdout) if completed.returncode == 0 else {
        "oracle_passed": False, "stderr": completed.stderr[-2000:]}
    return {"compiled": True, "process_exit": completed.returncode,
            "model_execution_established": False, **result}


def _target(result: object, aliases: Mapping[str, list[str]]) -> str:
    if isinstance(result, str):
        path = result
    elif isinstance(result, Mapping):
        path = result.get("target", result.get("path"))
        if not isinstance(path, str):
            raise ValueError("retrieval result lacks a target or path")
    else:
        raise ValueError("unsupported retrieval result")
    path = path.split("#", 1)[0]
    if path in aliases:
        return path
    for owner, paths in aliases.items():
        if path in paths:
            return owner
    # Unmapped results remain in the precision denominator, never as relevance.
    return "unmapped:" + path


def score_retrieval(manifest: Mapping[str, Any], observations: Mapping[str, Any], *,
                    split: str | None = None) -> dict[str, Any]:
    """Deduplicate source owners before top five; retain missing observations.

    Values can be result lists, or objects with `results` and an explicit boolean
    `definitive_answer`. Without that boolean, no answer-claim evidence is inferred.
    Unsupported questions are reported separately from answerable precision.
    """
    if split not in {None, "development", "held-out"}:
        raise ValueError("unsupported retrieval split")
    retrieval = manifest["retrieval"]
    queries = [q for q in retrieval["queries"] if split is None or q["split"] == split]
    expected_ids = {q["id"] for q in queries}
    if set(observations) - expected_ids:
        raise ValueError("observations contain an unselected or unknown query")
    recovered = expected_total = relevant_returned = returned_total = 0
    exact_total = exact_correct = unsupported = candidate_queries = claim_observations = claim_count = 0
    rows = []
    for query in queries:
        raw = observations.get(query["id"], [])
        definitive = None
        if isinstance(raw, Mapping):
            results = raw.get("results", [])
            definitive = raw.get("definitive_answer")
            if definitive is not None and type(definitive) is not bool:
                raise ValueError("definitive answer observation must be a boolean")
        else:
            results = raw
        if not isinstance(results, Sequence) or isinstance(results, (str, bytes)):
            raise ValueError("retrieval results must be a sequence")
        aliases = retrieval["target_aliases"][query["project"]]
        distinct = list(dict.fromkeys(_target(result, aliases) for result in results))[:5]
        expected = set(query["expected_targets"])
        hits = len(expected.intersection(distinct))
        row = {"query_id": query["id"], "split": query["split"], "category": query["category"],
               "targets_at_five": distinct, "expected_targets": sorted(expected),
               "recovered": hits, "observation_missing": query["id"] not in observations,
               "definitive_answer": definitive}
        if expected:
            expected_total += len(expected)
            recovered += hits
            relevant_returned += hits
            returned_total += len(distinct)
        else:
            unsupported += 1
            candidate_queries += bool(distinct)
            if definitive is not None:
                claim_observations += 1
                claim_count += definitive
        if query["category"] == "exact-symbol":
            exact_total += 1
            correct = bool(distinct) and distinct[0] == query["expected_top_one"]
            exact_correct += correct
            row["top_one_correct"] = correct
        rows.append(row)
