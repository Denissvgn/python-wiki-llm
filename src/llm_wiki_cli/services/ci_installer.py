MANAGED_WORKFLOW_PATH = Path(".github/workflows/llm-wiki-integrity.yml")
DOCUMENTATION_WORKFLOW_PATH = Path(".github/workflows/llm-wiki-candidate.yml")
MANAGED_WORKFLOW_SCHEMA = "llm-wiki-install-ci/v1"
DOCUMENTATION_WORKFLOW_SCHEMA = "llm-wiki-install-ci/documentation/v1"
CHECKOUT_ACTION_REF = "d23441a48e516b6c34aea4fa41551a30e30af803"
WIKI_INTEGRITY_ACTION = "Denissvgn/python-wiki-llm/integrations/wiki-integrity"
WIKI_CANDIDATE_ACTION = "Denissvgn/python-wiki-llm/integrations/wiki-candidate"

_ACTION_REF_RE = re.compile(r"^[0-9a-fA-F]{40}$", re.ASCII)
_MANAGED_HEADER_RE = re.compile(
    rf"\A# Generated by llm-wiki install-ci; do not edit\.\n"
    rf"# llm-wiki-managed: ({re.escape(MANAGED_WORKFLOW_SCHEMA)}|{re.escape(DOCUMENTATION_WORKFLOW_SCHEMA)})\n"
    r"# llm-wiki-content-sha256: ([0-9a-f]{64})\n\n",
    re.ASCII,
)


class InstallCiError(ValueError):
    """Raised when a portable CI workflow cannot be installed safely."""


@dataclass(frozen=True)
class InstallCiResult:
    """Outcome of one workflow installation attempt."""

    path: Path
    operation: str
    action_ref: str
    dry_run: bool

    @property
    def changed(self) -> bool:
        return self.operation != "unchanged" and not self.dry_run


def normalize_action_ref(value: object) -> str:
    """Return a canonical immutable Git commit for the reusable action."""

    if not isinstance(value, str) or _ACTION_REF_RE.fullmatch(value) is None:
        raise InstallCiError("--action-ref must be exactly 40 hexadecimal characters")
    return value.lower()


def _validated_project_path(value: object, *, label: str) -> str:
    return require_repository_relative_path(
        value,
        text_error=InstallCiError(f"{label} must be a non-empty project-relative path"),
        posix_error=InstallCiError(f"{label} must use portable POSIX path spelling"),
        normalized_error=InstallCiError(
            f"{label} must be a normalized project-relative path"
        ),
        absolute_error=InstallCiError(
            f"{label} must be project-relative for a portable workflow"
        ),
        separator_error=InstallCiError(
            f"{label} must use portable POSIX '/' separators"
        ),
        control_error=InstallCiError(f"{label} must not contain control characters"),
        reject_delete_character=True,
        leading_backslash_is_absolute=True,
        portability_error=InstallCiError(
            f"{label} must be portable across supported filesystems"
        ),
    )


def _without_github_expression(path: str, *, label: str) -> str:
    if "${{" in path:
        raise InstallCiError(f"{label} must not contain a GitHub Actions expression")
    return path


def _portable_project_path(value: object, *, label: str, allow_root: bool) -> str:
    if value == "." and allow_root:
        return "."
    return _without_github_expression(
        _validated_project_path(value, label=label),
        label=label,
    )


def _project_directory(
    project_root: Path,
    relative_path: str,
    *,
    label: str,
) -> Path:
    if relative_path == ".":
        candidate = project_root
    else:
        try:
            candidate = locate_exact_repository_path(project_root, relative_path)
        except SourceSelectionError as exc:
            raise InstallCiError(
                f"{label} is not an exact portable path: {exc}"
            ) from exc
        if candidate is None:
            raise InstallCiError(f"{label} does not name an existing directory")
    unsafe = first_unsafe_path_component(candidate)
    if unsafe is not None:
        try:
            display = unsafe.relative_to(project_root)
        except ValueError:
            display = unsafe
        raise InstallCiError(f"{label} crosses an unsafe path component: {display}")
    try:
        resolved = candidate.resolve()
        resolved.relative_to(project_root)
    except (OSError, RuntimeError, ValueError) as exc:
        raise InstallCiError(f"{label} resolves outside the project") from exc
    if not resolved.is_dir():
        raise InstallCiError(f"{label} does not name an existing directory")
    return resolved


def _validate_default_selection_contract(source_root: Path, wiki_dir: Path) -> None:
    """Prove the managed wiki can use default source-selection discovery."""

    manifest_path = wiki_dir / MANIFEST_FILENAME
    unsafe = first_unsafe_path_component(manifest_path)
    if unsafe is not None or not manifest_path.is_file():
        raise InstallCiError(
            "managed wiki manifest must be a regular file without symlink or "
            "reparse components"
        )
    try:
        manifest = SyncManifest.load(wiki_dir)
        policy = resolve_source_selection(source_root, None)
        validate_persisted_source_selection_identity(
            manifest.generation_inputs,
            None if policy is None else policy.identity,
            operation="install-ci",
        )
    except (
        FileNotFoundError,
        OSError,
        UnicodeError,
        ValueError,
        SourceSelectionError,
        SyncManifestError,
    ) as exc:
        raise InstallCiError(
            f"managed wiki is not valid for default source-selection discovery: {exc}"
        ) from exc


def _workflow_body(*, action_ref: str, src_dir: str, wiki_dir: str) -> str:
    source_value = json.dumps(src_dir)
    wiki_value = json.dumps(wiki_dir)
    return f"""name: LLM Wiki integrity

on:
  push:
  pull_request:

permissions:
  contents: read

jobs:
  integrity:
    name: LLM Wiki integrity
    runs-on: ubuntu-24.04
    timeout-minutes: 45
    permissions:
      contents: read
    steps:
      - name: Check out the repository without credentials
        uses: actions/checkout@{CHECKOUT_ACTION_REF} # v6.1.0
        with:
          persist-credentials: false
          fetch-depth: 0

      - name: Check LLM Wiki integrity
        uses: {WIKI_INTEGRITY_ACTION}@{action_ref}
        with:
          src-dir: {source_value}
          wiki-dir: {wiki_value}
          report-schema: v4
          comparison-policy: auto
          impact-base: ${{{{ github.event.pull_request.base.sha }}}}
          impact-head: ${{{{ github.event.pull_request.head.sha }}}}
"""


def render_managed_workflow(
    *,
    action_ref: str,
    src_dir: str = ".",
    wiki_dir: str = "docs/llm_wiki",
) -> bytes:
    """Render deterministic workflow bytes with a self-verifying owner marker."""

    canonical_ref = normalize_action_ref(action_ref)
    source_path = _portable_project_path(src_dir, label="--src-dir", allow_root=True)
    wiki_path = _portable_project_path(wiki_dir, label="--wiki-dir", allow_root=False)
    body = _workflow_body(
        action_ref=canonical_ref,
        src_dir=source_path,
        wiki_dir=wiki_path,
    )
    return _with_ownership_checksum(body)


def _with_ownership_checksum(body: str, schema: str = MANAGED_WORKFLOW_SCHEMA) -> bytes:
    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()
    header = (
        "# Generated by llm-wiki install-ci; do not edit.\n"
        f"# llm-wiki-managed: {schema}\n"
        f"# llm-wiki-content-sha256: {digest}\n\n"
    )
    return (header + body).encode("utf-8")


def _normalize_newlines(content: bytes) -> bytes | None:
    try:
        text = content.decode("utf-8")
    except UnicodeDecodeError:
        return None
    return text.replace("\r\n", "\n").replace("\r", "\n").encode("utf-8")


def is_unmodified_managed_workflow(
    content: bytes, *, workflow_path: Path | None = None
) -> bool:
    """Return whether bytes carry a valid installer ownership checksum."""

    normalized = _normalize_newlines(content)
    if normalized is None:
        return False
    text = normalized.decode("utf-8")
    match = _MANAGED_HEADER_RE.match(text)
    if match is None:
        return False
    if workflow_path is not None:
        schemas = {
            MANAGED_WORKFLOW_PATH: MANAGED_WORKFLOW_SCHEMA,
            DOCUMENTATION_WORKFLOW_PATH: DOCUMENTATION_WORKFLOW_SCHEMA,
        }
        if match.group(1) != schemas.get(workflow_path):
            return False
    body = text[match.end() :].encode("utf-8")
    actual = hashlib.sha256(body).hexdigest()
    return hmac.compare_digest(match.group(2), actual)


def _validate_workflow_target(project_root: Path, workflow_path: Path) -> Path:
    target = project_root / workflow_path
    for prefix in (
        ".github",
        ".github/workflows",
        workflow_path.as_posix(),
    ):
        try:
            existing = locate_exact_repository_path(project_root, prefix)
        except SourceSelectionError as exc:
            raise InstallCiError(f"workflow target is not portable: {exc}") from exc
        if existing is None:
            break
    unsafe = first_unsafe_path_component(target)
    if unsafe is not None:
        try:
            display = unsafe.relative_to(project_root)
        except ValueError:
            display = unsafe
        raise InstallCiError(
            f"workflow target crosses an unsafe path component: {display}"
        )
    if target.exists() and not target.is_file():
        raise InstallCiError(f"workflow target is not a regular file: {workflow_path}")
    return target


def install_ci_workflow(
    *,
    action_ref: str,
    src_dir: str = ".",
    wiki_dir: str = "docs/llm_wiki",
    dry_run: bool = False,
    force: bool = False,
    project_root: str | Path | None = None,
) -> InstallCiResult:
    """Create or safely update the repository's managed integrity workflow."""

    canonical_ref = normalize_action_ref(action_ref)
    source_path = _portable_project_path(src_dir, label="--src-dir", allow_root=True)
    wiki_path = _portable_project_path(wiki_dir, label="--wiki-dir", allow_root=False)
    root = _project_root(project_root)
    source_root = _project_directory(root, source_path, label="--src-dir")
    managed_wiki = _project_directory(root, wiki_path, label="--wiki-dir")
    state = classify_wiki_lifecycle(managed_wiki)
    if state is not WikiLifecycleState.MANAGED:
        raise InstallCiError(
            "install-ci requires an initialized managed wiki with "
            f"{MANIFEST_FILENAME}; run llm-wiki bootstrap first"
        )
    _validate_default_selection_contract(source_root, managed_wiki)

    desired = render_managed_workflow(
        action_ref=canonical_ref,
        src_dir=source_path,
        wiki_dir=wiki_path,
    )
    return _install_workflow(
        root,
        MANAGED_WORKFLOW_PATH,
        desired,
        canonical_ref,
        dry_run=dry_run,
        force=force,
    )


def install_documentation_ci_workflow(
    *,
    action_ref: str,
    config: str = PUBLICATION_CONFIG_PATH,
    working_directory: str = ".",
    src_dir: str | None = None,
    target_dir: str | None = None,
    baseline: str | None = None,
    reviews: str | None = None,
    previous_receipt: str | None = None,
    candidate_review: str | None = None,
    require_ready: bool = False,
    dry_run: bool = False,
    force: bool = False,
    project_root: str | Path | None = None,
) -> InstallCiResult:
    """Install a read-only candidate workflow for a configured consumer project."""
    if any(type(value) is not bool for value in (require_ready, force, dry_run)):
        raise InstallCiError("require_ready, force and dry_run must be booleans")
    root = _project_root(project_root)
    canonical_ref = normalize_action_ref(action_ref)
    selected = (
        _portable_project_path(src_dir, label="--src-dir", allow_root=True)
        if src_dir is not None
        else None
    )
    inputs = {
        "working-directory": _portable_project_path(
            working_directory, label="--working-directory", allow_root=True
        ),
        "src-dir": selected or ".",
        "config": _portable_project_path(config, label="--config", allow_root=False),
    }
    consumer = _project_directory(
        root, inputs["working-directory"], label="--working-directory"
    )
    try:
        policy = load_publication_config(consumer, config_path=inputs["config"])
        if policy["architecture"]["baseline"] == "existing-wiki":
            inputs["src-dir"] = _portable_project_path(
                publication_source_root(policy["architecture"], selected),
                label="--src-dir",
                allow_root=True,
            )
        source_root = _project_directory(consumer, inputs["src-dir"], label="--src-dir")
        if "content" not in policy:
            raise InstallCiError(
                "Documentation CI requires a publication content mapping"
            )
        architecture = _project_directory(
            consumer, policy["architecture"]["root"], label="architecture.root"
        )
        if policy["architecture"]["baseline"] == "existing-wiki":
            _validate_default_selection_contract(source_root, architecture)
        _project_directory(consumer, policy["content"]["root"], label="content.root")
        authored = [
            topic["source_document"]
            for topic in policy["topics"]
            if topic["edit_at"] == "repository"
        ]
        authored.extend(
            asset["source_document"] for asset in policy["content"].get("assets", [])
        )
        protected = [consumer / config]
        for source in authored:
            path = publication_path(consumer, source)
            if not path.is_file():
                raise InstallCiError(f"Mapped source is not a regular file: {source}")
            protected.append(path)

        target = None
        if target_dir is not None:
            inputs["target-dir"] = _portable_project_path(
                target_dir, label="--target-dir", allow_root=False
            )
            target = _project_directory(
                consumer, inputs["target-dir"], label="--target-dir"
            )
            protected.append(target)
        for name, argument in (
            ("baseline", baseline),
            ("reviews", reviews),
            ("previous-receipt", previous_receipt),
            ("candidate-review", candidate_review),
        ):
            if argument is None:
                continue
            inputs[name] = _portable_project_path(
                argument, label="--" + name, allow_root=False
            )
            path = publication_path(consumer, inputs[name])
            if not path.is_file():
                raise InstallCiError(f"--{name} must name a regular accepted artifact")
            if target is not None and publication_control_overlap(target, path):
                raise InstallCiError(f"--{name} must stay outside the public target")
            protected.append(path)
        if any(
            publication_control_overlap(root / DOCUMENTATION_WORKFLOW_PATH, path)
            for path in protected
        ):
            raise InstallCiError(
                "The documentation workflow path overlaps a publication input"
            )
    except PublicationConfigError as exc:
        raise InstallCiError(f"Invalid publication configuration: {exc}") from exc
    if require_ready:
        inputs["fail-on"] = "review-required"
    return _install_workflow(
        root,
        DOCUMENTATION_WORKFLOW_PATH,
        _documentation_workflow(canonical_ref, inputs),
        canonical_ref,
        dry_run=dry_run,
        force=force,
    )


def _documentation_workflow(action_ref: str, inputs: dict[str, str]) -> bytes:
    action_inputs = "\n".join(
        f"          {key}: {json.dumps(value)}" for key, value in inputs.items()
    )
    body = f"""name: GitHub wiki candidate

on:
  pull_request:
  push:
  workflow_dispatch:
    inputs:
      source-revision:
        description: Full source commit to recheck with the accepted records on the dispatch ref
        type: string
        required: false

permissions:
  contents: read

jobs:
  candidate:
    runs-on: ubuntu-24.04
    timeout-minutes: 45
    steps:
      - name: Check out the candidate without credentials
        uses: actions/checkout@{CHECKOUT_ACTION_REF} # v6.1.0
        with:
          ref: ${{{{ inputs.source-revision || github.sha }}}}
          persist-credentials: false
          fetch-depth: 0

      - name: Prepare and check the wiki candidate
        uses: {WIKI_CANDIDATE_ACTION}@{action_ref}
        with:
{action_inputs}
          source-revision: ${{{{ inputs.source-revision || github.sha }}}}
          accepted-state-revision: ${{{{ github.event_name == 'workflow_dispatch' && github.sha || '' }}}}
"""
    return _with_ownership_checksum(body, DOCUMENTATION_WORKFLOW_SCHEMA)


def _project_root(project_root: str | Path | None) -> Path:
    try:
        root = (Path.cwd() if project_root is None else Path(project_root)).resolve()
    except (OSError, RuntimeError, ValueError) as exc:
        raise InstallCiError("project root cannot be resolved") from exc
    if not root.is_dir():
        raise InstallCiError("project root must be an existing directory")
    return root


def _install_workflow(
    root: Path,
    workflow_path: Path,
    desired: bytes,
    canonical_ref: str,
    *,
    dry_run: bool,
    force: bool,
) -> InstallCiResult:
    target = _validate_workflow_target(root, workflow_path)
    try:
        existing = target.read_bytes() if target.exists() else None
    except OSError as exc:
        raise InstallCiError(
            f"cannot read managed workflow {workflow_path}: {exc}"
        ) from exc
    normalized_existing = (
        _normalize_newlines(existing) if existing is not None else None
    )
    if normalized_existing == desired:
        return InstallCiResult(
            path=workflow_path,
            operation="unchanged",
            action_ref=canonical_ref,
            dry_run=dry_run,
        )

    operation = "create" if existing is None else "update"
    if (
        existing is not None
        and not is_unmodified_managed_workflow(existing, workflow_path=workflow_path)
        and not force
    ):
        raise InstallCiError(
            f"{workflow_path} exists and is not an unmodified "
            "llm-wiki managed workflow; rerun with --force to replace it"
        )

    if not dry_run:
        try:
            ensure_guarded_directory(target.parent)
            atomic_write_guarded_bytes(target, desired, expected_existing=existing)
        except OSError as exc:
            raise InstallCiError(
                f"cannot write managed workflow {workflow_path}: {exc}"
            ) from exc
    return InstallCiResult(
        path=workflow_path,
        operation=operation,
        action_ref=canonical_ref,
        dry_run=dry_run,
    )


